# Every source file that can carry a comment starts with an SPDX licence line
# and a copyright line. Usage: check-headers.sh [directory]; the default is the
# repository this script lives in. Checks the first HEAD_LINES lines of every
# tracked file and every new file git does not ignore, whatever its name.
#
# Fails when the directory is not inside a git work tree, and when no file at
# all was checked, so a broken listing cannot pass as a clean one.
#
# Checked: .rs .sh .py .yml .yaml .toml, and the file .gitignore. Not checked,
# because the format cannot hold a comment or is not source: .json and the
# lockfiles, Markdown, images, VERSION and LICENSE. Exempt by path, because the
# bytes are not ours to edit:
#   crates/*/permissions/autogenerated/  written by tauri-plugin's build script
#                                        on every build
#   crates/*/tests/data*/                fixtures whose exact bytes are the
#                                        input a test parses
#   testdata/                            the round-trip corpus

set -euo pipefail

cd "${1:-"$(dirname "$0")/.."}"

HEAD_LINES=5
SPDX='SPDX-License-Identifier: AGPL-3.0-or-later'
COPYRIGHT='Copyright (c) 2026 Sricharan Suresh (github.com/verycareful)'

if ! git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
    echo "error: $PWD is not inside a git work tree" >&2
    exit 1
fi
# Fails here, under set -e, if the listing itself cannot be made.
git ls-files -z -co --exclude-standard >/dev/null

status=0
checked=0
while IFS= read -r -d '' f; do
    case "$f" in
        crates/*/permissions/autogenerated/* | crates/*/tests/data*/* | testdata/*) continue ;;
    esac
    case "$f" in
        *.rs | *.sh | *.py | *.yml | *.yaml | *.toml | .gitignore | */.gitignore) ;;
        *) continue ;;
    esac
    [[ -f $f ]] || continue
    checked=$((checked + 1))
    head=$(head -n "$HEAD_LINES" -- "$f")
    for want in "$SPDX" "$COPYRIGHT"; do
        if ! grep -qF -- "$want" <<<"$head"; then
            printf "error: %s: no '%s' in the first %s lines\n" "$f" "$want" "$HEAD_LINES" >&2
            status=1
        fi
    done
done < <(git ls-files -z -co --exclude-standard)

if [[ $checked -eq 0 ]]; then
    echo "error: no source files found to check" >&2
    exit 1
fi
[[ $status -eq 0 ]] && echo "ok: $checked source files have their header"
exit "$status"
