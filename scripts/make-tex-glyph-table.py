"""Write the glyph names of the TeX fonts and the text each stands for.

    python3 -I scripts/make-tex-glyph-table.py \
        glyphtounicode-cmr.tex glyphlist.txt \
        crates/kernkraft-pdf/src/font/data/texglyphs.rs

glyphtounicode-cmr.tex is the file of the `pdfx` package (TeX Live, CTAN
macros/latex/contrib/pdfx) that gives each glyph name of Computer Modern,
the math extension and symbol fonts and the XY-pic fonts the text it stands
for, as lines `\\pdfglyphtounicode{name}{codes}`. glyphlist.txt is the Adobe
Glyph List the font module reads first.

Four changes are made, and the file the table is made from is otherwise
kept as it is:

* A name that is a letter and a number (`a1`, `d47`) is left out: ZapfDingbats
  names its glyphs `a1` to `a206`, and a subset font of any producer may
  number its glyphs `d47`, so such a name read without the font would give
  the text of another font's glyph.
* A name the Adobe Glyph List has is kept only when every character it
  gives is in the private use area (U+E000 to U+F8FF), which is no text;
  the TeX file's characters stand for it. Every other name of the Adobe
  Glyph List keeps the list's value.
* A name whose characters are all in the private use area is left out too:
  that is no text, whatever the Adobe Glyph List has for the name.
* The variation selectors U+FE00 to U+FE0F that end the value of a size
  variant (`parenleftbig` is `0028 FE01`) are removed: the text is the
  character.
"""

import re
import sys

PRIVATE_USE = range(0xE000, 0xF900)
VARIATION_SELECTORS = range(0xFE00, 0xFE10)
PER_LINE = 3
NUMBERED = re.compile(r"^[A-Za-z][0-9]+$")

LINE = re.compile(r"^\\pdfglyphtounicode\{([^}]+)\}\{([0-9A-F ]+)\}")

HEADER = [
    "// SPDX-License-Identifier: AGPL-3.0-or-later",
    "// Copyright (c) 2026 Sricharan Suresh (github.com/verycareful)",
    "",
    "//! The glyph names of the TeX fonts (Computer Modern, the math extension and",
    "//! symbol fonts, the XY-pic fonts) and the text each stands for.",
    "//!",
    "//! Generated by `scripts/make-tex-glyph-table.py`; do not edit by hand.",
    "//! Source: glyphtounicode-cmr.tex of the `pdfx` package (TeX Live; CTAN,",
    "//! macros/latex/contrib/pdfx), Copyright (c) 2008 Han The Thanh, 2014 Peter",
    "//! Selinger, 2018 Ross Moore, distributed under the LaTeX Project Public",
    "//! License, version 1.2 or later. This table holds part of that file and",
    "//! was changed from it: only the names that the Adobe Glyph List lacks, or",
    "//! gives only private use characters for, are kept, and a name that is a",
    "//! letter and a number (`a1`, `d47`) is left out, since another font may",
    "//! give it another glyph, and so is a name the source gives only private",
    "//! use characters; the variation selectors U+FE00 to U+FE0F that end",
    "//! some values are removed, so that `parenleftbig` is `(`; the data is a",
    "//! Rust table. The authors of the source give no support for this table. A",
    "//! complete, unmodified copy of the source is distributed with TeX Live's",
    "//! `pdfx` package and with CTAN.",
    "//! Sorted by name, bytewise, for binary search.",
]


def read_tex(path):
    names = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            found = LINE.match(line)
            if not found:
                continue
            codes = [int(code, 16) for code in found[2].split()]
            codes = [code for code in codes if code not in VARIATION_SELECTORS]
            if codes:
                names[found[1]] = "".join(chr(code) for code in codes)
    return names


def read_adobe(path):
    names = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or ";" not in line:
                continue
            name, codes = line.strip().split(";")
            names[name] = "".join(chr(int(code, 16)) for code in codes.split())
    return names


def escaped(text):
    return "".join(f"\\u{{{ord(c):04X}}}" for c in text)


def main():
    if len(sys.argv) != 4:
        sys.exit("usage: make-tex-glyph-table.py glyphtounicode-cmr.tex glyphlist.txt OUTPUT.rs")
    tex = read_tex(sys.argv[1])
    adobe = read_adobe(sys.argv[2])
    kept = sorted(
        (name, text)
        for name, text in tex.items()
        if not NUMBERED.match(name)
        and not all(ord(c) in PRIVATE_USE for c in text)
        and (name not in adobe or all(ord(c) in PRIVATE_USE for c in adobe[name]))
    )
    lines = HEADER + [
        "",
        "#[rustfmt::skip]",
        f"pub(crate) static TEX_GLYPH_LIST: [(&str, &str); {len(kept)}] = [",
    ]
    for start in range(0, len(kept), PER_LINE):
        chunk = kept[start : start + PER_LINE]
        lines.append(
            "    " + " ".join(f'("{name}", "{escaped(text)}"),' for name, text in chunk)
        )
    lines.append("];")
    with open(sys.argv[3], "w", encoding="utf-8") as out:
        out.write("\n".join(lines) + "\n")
    print(f"{len(kept)} names kept of {len(tex)}", file=sys.stderr)


main()
