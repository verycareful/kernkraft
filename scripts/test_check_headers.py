"""Tests for check-headers.sh. Run: python3 -I scripts/test_check_headers.py

Each case builds a small git repository under the repo's local/ directory
(ignored by git, never the system temp directory) and runs the script on it.
"""

import os
import subprocess
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
SCRIPT = os.path.join(HERE, "check-headers.sh")
SCRATCH = os.path.join(REPO, "local", "scratchpad-scripts")

SPDX = "SPDX-License-Identifier: AGPL-3.0-or-later"
COPY = "Copyright (c) 2026 Sricharan Suresh (github.com/verycareful)"


def header(prefix: str = "// ", suffix: str = "") -> str:
    return f"{prefix}{SPDX}{suffix}\n{prefix}{COPY}{suffix}\n"


def run(root: str) -> subprocess.CompletedProcess:
    env = dict(os.environ)
    # Keep git from finding the enclosing repository when the case is a plain directory.
    env["GIT_CEILING_DIRECTORIES"] = SCRATCH
    return subprocess.run(
        ["bash", SCRIPT, root], capture_output=True, text=True, env=env, check=False
    )


class CheckHeaders(unittest.TestCase):
    def setUp(self) -> None:
        os.makedirs(SCRATCH, exist_ok=True)
        self._tmp = tempfile.TemporaryDirectory(dir=SCRATCH)
        self.addCleanup(self._tmp.cleanup)
        self.root = self._tmp.name

    def write(self, name: str, text: str) -> None:
        path = os.path.join(self.root, name)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)

    def git_init(self) -> None:
        subprocess.run(["git", "init", "-q", self.root], check=True)

    def expect_fail(self, name: str) -> str:
        r = run(self.root)
        self.assertEqual(r.returncode, 1, r.stdout + r.stderr)
        self.assertIn(name, r.stderr)
        return r.stderr

    def test_all_headers_present_passes(self) -> None:
        self.git_init()
        self.write("a.rs", header() + "fn main() {}\n")
        self.write("crates/x/src/b.rs", header() + "\n")
        self.write("run.sh", "#!/usr/bin/env bash\n" + header("# "))
        self.write(".gitignore", header("# ") + "target\n")
        self.write("Cargo.toml", header("# ") + "[package]\n")
        self.write("ci.yml", header("# ") + "name: CI\n")
        r = run(self.root)
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertIn("ok", r.stdout)

    def test_missing_spdx_line(self) -> None:
        self.git_init()
        self.write("a.rs", f"// {COPY}\nfn main() {{}}\n")
        self.assertIn(SPDX, self.expect_fail("a.rs"))

    def test_missing_copyright_line(self) -> None:
        self.git_init()
        self.write("a.rs", f"// {SPDX}\nfn main() {{}}\n")
        self.assertIn(COPY, self.expect_fail("a.rs"))

    def test_test_file_without_header(self) -> None:
        self.git_init()
        self.write("ok.rs", header())
        self.write("crates/x/tests/t.rs", "#[test]\nfn t() {}\n")
        self.expect_fail("crates/x/tests/t.rs")

    def test_other_kinds_without_header(self) -> None:
        # Every kind the script claims to check, as check-headers.sh lists them.
        extensions = "rs sh py yml yaml toml".split()
        names = [f"a.{ext}" for ext in extensions]
        names += [".gitignore", "sub/.gitignore"]
        for name in names:
            with self.subTest(name=name):
                case_dir = tempfile.TemporaryDirectory(dir=SCRATCH)
                self.addCleanup(case_dir.cleanup)
                self.root = case_dir.name
                self.git_init()
                self.write(name, "x\n")
                self.expect_fail(name)

    def test_generated_permission_files_are_not_checked(self) -> None:
        self.git_init()
        self.write("ok.rs", header())
        self.write("crates/x/permissions/autogenerated/commands/a.toml", "x\n")
        r = run(self.root)
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)

    def test_fixture_directories_are_checked_like_any_other(self) -> None:
        self.git_init()
        self.write("ok.rs", header())
        self.write("crates/x/tests/data/apps/a.toml", "x\n")
        self.expect_fail("crates/x/tests/data/apps/a.toml")

    def test_exemption_is_by_path_not_by_name(self) -> None:
        self.git_init()
        self.write("ok.rs", header())
        self.write("crates/x/permissions/default.toml", "x\n")
        self.expect_fail("crates/x/permissions/default.toml")
        self.write("crates/x/src/data.rs", "x\n")
        self.assertIn("crates/x/src/data.rs", run(self.root).stderr)

    def test_non_ascii_name_is_checked(self) -> None:
        self.git_init()
        self.write("ok.rs", header())
        self.write("src/ä.rs", "export {};\n")
        self.expect_fail("src/ä.rs")

    def test_non_ascii_name_with_header_passes(self) -> None:
        self.git_init()
        self.write("src/ä.rs", header())
        self.assertEqual(run(self.root).returncode, 0)

    def test_not_a_git_work_tree_fails(self) -> None:
        self.write("a.rs", header())
        r = run(self.root)
        self.assertNotEqual(r.returncode, 0)
        self.assertNotIn("ok", r.stdout)

    def test_zero_checked_files_fails(self) -> None:
        self.git_init()
        self.write("README.md", "# readme\n")
        self.write("data.json", "{}\n")
        r = run(self.root)
        self.assertEqual(r.returncode, 1, r.stdout + r.stderr)
        self.assertNotIn("ok", r.stdout)

    def test_ignored_files_are_not_checked(self) -> None:
        self.git_init()
        self.write(".gitignore", header("# ") + "skip.rs\n")
        self.write("skip.rs", "no header\n")
        self.write("a.rs", header())
        self.assertEqual(run(self.root).returncode, 0)


if __name__ == "__main__":
    unittest.main()
